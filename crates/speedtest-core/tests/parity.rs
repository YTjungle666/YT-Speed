//! 换算与上游 JS 的逐位对照。
//!
//! 期望值不是手算的：用 node 跑同一段公式生成
//! （`((bytes/secs)*8*factor/divisor).toFixed(2)`），再硬编码到这里。
//! 任何一处乘除顺序或取整方式变了，这些用例都会挂。

use speedtest_core::conv::{to_fixed2, Conv};

/// (bytes, secs, 十进兆 +1.06, 二进制兆 +1.06, 十进兆 +1.0)
const TABLE: &[(f64, f64, &str, &str, &str)] = &[
    (1_048_576.0, 1.0, "8.89", "8.48", "8.39"),
    (12_500_000.0, 1.0, "106.00", "101.09", "100.00"),
    (1_000_000_000.0, 7.3, "1161.64", "1107.83", "1095.89"),
    (734_003_200.0, 5.117, "1216.41", "1160.05", "1147.55"),
    (0.0, 1.0, "0.00", "0.00", "0.00"),
    (12.5, 8.0, "0.00", "0.00", "0.00"),
    (3.0, 0.2, "0.00", "0.00", "0.00"),
    (999.0, 1.1, "0.01", "0.01", "0.01"),
    (1_005_000.0, 8.0, "1.07", "1.02", "1.00"),
    (123_456_789.0, 9.87654321, "106.00", "101.09", "100.00"),
    (0.125, 1.0, "0.00", "0.00", "0.00"),
    (2_500_000_000.0, 14.993, "1413.99", "1348.49", "1333.96"),
    (7.0, 0.0007, "0.08", "0.08", "0.08"),
    (
        1_234_567_890_123.0,
        15.0,
        "697942.38",
        "665609.72",
        "658436.21",
    ),
];

#[test]
fn matches_upstream_formula_bit_for_bit() {
    let dec = Conv::default();
    let mib = Conv::mebibits();
    let raw = Conv {
        overhead: 1.0,
        divisor: 1_000_000.0,
    };
    for &(bytes, secs, want_dec, want_mib, want_raw) in TABLE {
        assert_eq!(dec.status(bytes, secs), want_dec, "十进制兆 {bytes}/{secs}");
        assert_eq!(mib.status(bytes, secs), want_mib, "二进制兆 {bytes}/{secs}");
        assert_eq!(raw.status(bytes, secs), want_raw, "无补偿 {bytes}/{secs}");
    }
}

#[test]
fn to_fixed2_matches_js_including_ties() {
    // 期望值来自 node：`v.toFixed(2)`
    let cases: &[(f64, &str)] = &[
        (0.125, "0.13"), // 恰好平局：JS 取较大值（half-up），不是 half-to-even
        (2.675, "2.67"), // 二进制里是 2.6749999…
        (1.005, "1.00"), // 同上，不能当成 1.01
        (0.005, "0.01"),
        (1.015, "1.01"),
        (-1.005, "-1.00"),
        (123.456, "123.46"),
        (0.1 + 0.2, "0.30"),
        (0.0, "0.00"),
        (-0.0, "0.00"),
        (9.999, "10.00"),
        (99.995, "100.00"), // 它的双精度值是 99.995000000000004547，刚好在平局之上
    ];
    for &(v, want) in cases {
        assert_eq!(to_fixed2(v), want, "{v}");
    }
    assert_eq!(to_fixed2(f64::NAN), "NaN");
    assert_eq!(to_fixed2(f64::INFINITY), "Infinity");
}
